const fs = require("fs");
const path = require("path");

const repoRoot = path.resolve(__dirname, "..");
const defaultPresets = path.resolve(repoRoot, "..", "Raidwise", "src", "data", "bis-presets");
const presetsDir = process.env.RAIDWISE_BIS_PRESETS || defaultPresets;
const outPath = path.join(repoRoot, "Raidwise", "GearCheckBis.lua");

const CLASS_FILE = {
  DeathKnight: "DEATHKNIGHT",
  Druid: "DRUID",
  Hunter: "HUNTER",
  Mage: "MAGE",
  Paladin: "PALADIN",
  Priest: "PRIEST",
  Rogue: "ROGUE",
  Shaman: "SHAMAN",
  Warlock: "WARLOCK",
  Warrior: "WARRIOR",
};

const SPEC_TAB = {
  WARRIOR: { Arms: 1, Fury: 2, Protection: 3 },
  PALADIN: { Holy: 1, Protection: 2, Retribution: 3 },
  HUNTER: { "Beast Mastery": 1, Marksmanship: 2, Survival: 3 },
  ROGUE: { Assassination: 1, Combat: 2, Subtlety: 3 },
  PRIEST: { Discipline: 1, Holy: 2, Shadow: 3 },
  DEATHKNIGHT: { Blood: 1, Frost: 2, Unholy: 3 },
  SHAMAN: { Elemental: 1, Enhancement: 2, Restoration: 3 },
  MAGE: { Arcane: 1, Fire: 2, Frost: 3 },
  WARLOCK: { Affliction: 1, Demonology: 2, Destruction: 3 },
  DRUID: { Balance: 1, Feral: 2, Restoration: 3 },
};

if (!fs.existsSync(presetsDir)) {
  console.error("BiS presets not found: " + presetsDir);
  console.error("Set RAIDWISE_BIS_PRESETS or clone github.com/sergimax/Raidwise next to this repo.");
  process.exit(1);
}

const files = fs.readdirSync(presetsDir).filter(function (name) {
  return name.endsWith(".ts") && name !== "index.ts";
});

const byKey = {};
let presetCount = 0;

files.forEach(function (name) {
  const text = fs.readFileSync(path.join(presetsDir, name), "utf8");
  const classMatch = text.match(/className:\s*ClassName\.(\w+)/);
  const specMatch = text.match(/spec:\s*"([^"]+)"/);
  if (!classMatch || !specMatch) {
    console.error("Skip " + name + ": missing className/spec");
    return;
  }
  const classFile = CLASS_FILE[classMatch[1]];
  const spec = specMatch[1];
  const tab = classFile && SPEC_TAB[classFile] && SPEC_TAB[classFile][spec];
  if (!classFile || !tab) {
    console.error("Skip " + name + ": no profile key for " + classMatch[1] + " / " + spec);
    return;
  }
  const key = classFile + "-" + tab;
  const ids = byKey[key] || {};
  const idMatches = text.matchAll(/itemIds:\s*\[([0-9,\s]+)\]/g);
  for (const match of idMatches) {
    match[1].split(",").forEach(function (part) {
      const id = parseInt(part.trim(), 10);
      if (id) {
        ids[id] = true;
      }
    });
  }
  byKey[key] = ids;
  presetCount += 1;
});

const keys = Object.keys(byKey).sort();
const lines = [
  "-- Generated by scripts/generate-gear-check-bis.js from Raidwise web-app BiS presets.",
  "-- Union of all built-in preset item IDs per spec (Kingdom / Titans / community).",
  "-- Regenerate when sibling repo src/data/bis-presets changes.",
  "-- Do not edit by hand.",
  "",
  "local Addon = Raidwise",
  "",
  "Addon.GearCheckBisIds = {",
];

keys.forEach(function (key) {
  const ids = Object.keys(byKey[key])
    .map(Number)
    .sort(function (a, b) {
      return a - b;
    });
  lines.push("\t[\"" + key + "\"] = {");
  ids.forEach(function (id) {
    lines.push("\t\t[" + id + "] = true,");
  });
  lines.push("\t},");
});

lines.push("}");
lines.push("");
lines.push("function Addon:IsGearCheckBisItem(classFile, specTab, itemId)");
lines.push("\titemId = tonumber(itemId)");
lines.push("\tspecTab = tonumber(specTab) or 0");
lines.push("\tif not itemId or specTab < 1 or not classFile then");
lines.push("\t\treturn false");
lines.push("\tend");
lines.push("\tlocal set = self.GearCheckBisIds[string.upper(classFile) .. \"-\" .. tostring(specTab)]");
lines.push("\treturn set and set[itemId] == true");
lines.push("end");
lines.push("");

fs.writeFileSync(outPath, lines.join("\n"), "utf8");
console.log("Wrote " + outPath + " (" + keys.length + " specs, " + presetCount + " preset files)");
